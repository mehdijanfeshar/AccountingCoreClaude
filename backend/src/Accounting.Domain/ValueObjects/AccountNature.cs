namespace Accounting.Domain.ValueObjects;

/// <summary>
/// ماهیت بدهکار/بستانکار یک معین (قانون ۲).
/// <see cref="Both"/> برای معین‌هایی است که ماهیت دوطرفه دارند (مثلاً حساب‌های واسط/تسویه)
/// و می‌توانند بسته به رخداد، بدهکار یا بستانکار شوند. توجه: در نسخهٔ فعلی، Nature صرفاً
/// یک برچسب اطلاعاتی/گزارشی روی معین است و در قوانین اعتبارسنجی سند (VoucherLine/Voucher)
/// دخالتی ندارد؛ محدودیت «فقط یکی از بدهکار/بستانکار در هر ردیف» مستقل از Nature و برای
/// همهٔ معین‌ها یکسان اعمال می‌شود (رجوع به chart-of-accounts.md).
/// </summary>
public enum AccountNature
{
    Debit = 1,
    Credit = 2,
    Both = 3
}
